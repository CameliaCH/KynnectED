-- Initial Supabase database migration. Run using scripts/migrate_supabase_database.py.
-- Historical account IDs deliberately have no profile FK: deleted accounts must
-- not remove or prevent importing retained lessons, messages or safeguarding history.
CREATE SCHEMA IF NOT EXISTS kynnected_private;
REVOKE ALL ON SCHEMA kynnected_private FROM PUBLIC, anon, authenticated, service_role;
SET LOCAL search_path TO public, kynnected_private, pg_catalog;

CREATE TABLE profiles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    auth_user_id UUID UNIQUE,
    username TEXT NOT NULL,
    email TEXT,
    role TEXT,
    school TEXT,
    is_coordinator BOOLEAN NOT NULL DEFAULT FALSE,
    data JSONB NOT NULL,
    CHECK (NOT (data ? 'password') AND NOT (data ? 'password_reset'))
);
CREATE UNIQUE INDEX profiles_username ON profiles(lower(username));
CREATE TABLE kynnected_private.account_credentials (
    account_id BIGINT PRIMARY KEY REFERENCES profiles(id) ON DELETE CASCADE,
    password_hash TEXT,
    reset_state JSONB
);
CREATE TABLE kynnected_private.reset_limits (
    key TEXT PRIMARY KEY,
    started DOUBLE PRECISION NOT NULL,
    count BIGINT NOT NULL
);
CREATE TABLE kynnected_private.migration_runs (
    name TEXT PRIMARY KEY,
    source_sha256 TEXT NOT NULL,
    imported_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    counts JSONB NOT NULL
);

CREATE TABLE lessons (
    id TEXT PRIMARY KEY,
    mentor_id BIGINT NOT NULL,
    mentee_id BIGINT NOT NULL,
    title TEXT NOT NULL,
    scheduled_at BIGINT NOT NULL,
    planned_minutes BIGINT NOT NULL,
    zoom_url TEXT NOT NULL,
    created_by BIGINT NOT NULL,
    created_at BIGINT NOT NULL,
    cancelled_at BIGINT,
    recording_filename TEXT,
    recording_original TEXT,
    recording_mimetype TEXT,
    recording_seconds DOUBLE PRECISION,
    recorded_at BIGINT,
    uploaded_by BIGINT,
    reviewed_at BIGINT,
    reviewed_by BIGINT,
    review_submitted_by BIGINT,
    reviewer_name TEXT,
    review_note TEXT
);
CREATE INDEX lessons_pair ON lessons(mentor_id, mentee_id, scheduled_at);
CREATE TABLE missing_recording_reports (
    rowid BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    lesson_id TEXT PRIMARY KEY REFERENCES lessons(id),
    mentor_id BIGINT NOT NULL,
    reason TEXT NOT NULL,
    note TEXT NOT NULL DEFAULT '',
    submitted_at BIGINT NOT NULL
);
CREATE INDEX missing_recording_reports_mentor ON missing_recording_reports(mentor_id);
CREATE TABLE resource_materials (
    rowid BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    id TEXT PRIMARY KEY,
    folder TEXT NOT NULL,
    title TEXT NOT NULL,
    filename TEXT NOT NULL,
    original_filename TEXT NOT NULL,
    mimetype TEXT NOT NULL,
    size_bytes BIGINT NOT NULL,
    uploaded_by BIGINT NOT NULL,
    uploaded_at BIGINT NOT NULL,
    status TEXT NOT NULL DEFAULT 'pending' CHECK(status IN ('pending', 'approved', 'rejected')),
    reviewed_by BIGINT,
    reviewed_at BIGINT,
    review_note TEXT NOT NULL DEFAULT ''
);
CREATE INDEX resource_materials_folder ON resource_materials(folder, status, uploaded_at);
CREATE TABLE messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mentor_id BIGINT NOT NULL,
    mentee_id BIGINT NOT NULL,
    sender_id BIGINT NOT NULL,
    body TEXT NOT NULL,
    created_at BIGINT NOT NULL
);
CREATE INDEX messages_pair ON messages(mentor_id, mentee_id, id);
CREATE TABLE recordings (
    rowid BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    id TEXT PRIMARY KEY,
    session_id TEXT NOT NULL REFERENCES lessons(id),
    mentor_id BIGINT NOT NULL,
    mentee_id BIGINT NOT NULL,
    r2_object_key TEXT NOT NULL UNIQUE,
    original_filename TEXT NOT NULL,
    content_type TEXT NOT NULL,
    file_size BIGINT NOT NULL,
    uploaded_at BIGINT NOT NULL,
    expires_at BIGINT NOT NULL,
    review_status TEXT NOT NULL DEFAULT 'awaiting_review'
        CHECK(review_status IN ('awaiting_review', 'reviewed', 'flagged')),
    reviewed_by BIGINT,
    reviewed_at BIGINT,
    review_submitted_by BIGINT,
    reviewer_name TEXT,
    review_note TEXT NOT NULL DEFAULT '',
    safeguarding_flag BIGINT NOT NULL DEFAULT 0,
    flagged_at BIGINT,
    flagged_by BIGINT,
    safeguarding_note TEXT NOT NULL DEFAULT '',
    active BIGINT NOT NULL DEFAULT 1
);
CREATE UNIQUE INDEX recordings_active ON recordings(session_id) WHERE active = 1;
CREATE TABLE recording_uploads (
    id TEXT PRIMARY KEY,
    session_id TEXT NOT NULL REFERENCES lessons(id),
    mentor_id BIGINT NOT NULL,
    r2_object_key TEXT NOT NULL UNIQUE,
    multipart_id TEXT NOT NULL,
    original_filename TEXT NOT NULL,
    content_type TEXT NOT NULL,
    file_size BIGINT NOT NULL,
    baseline TEXT NOT NULL,
    consent_at BIGINT NOT NULL,
    created_at BIGINT NOT NULL,
    status TEXT NOT NULL DEFAULT 'pending'
        CHECK(status IN ('pending', 'processing', 'completed', 'aborted')),
    processing_at BIGINT
);
CREATE UNIQUE INDEX recording_uploads_active ON recording_uploads(session_id)
    WHERE status IN ('pending', 'processing');

-- Flask uses its server connection and checks permissions on every request.
-- No table is exposed through the Data API until Auth policies are implemented.
ALTER TABLE profiles ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE profiles FROM PUBLIC, anon, authenticated, service_role;
ALTER TABLE lessons ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE lessons FROM PUBLIC, anon, authenticated, service_role;
ALTER TABLE missing_recording_reports ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE missing_recording_reports FROM PUBLIC, anon, authenticated, service_role;
ALTER TABLE resource_materials ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE resource_materials FROM PUBLIC, anon, authenticated, service_role;
ALTER TABLE messages ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE messages FROM PUBLIC, anon, authenticated, service_role;
ALTER TABLE recordings ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE recordings FROM PUBLIC, anon, authenticated, service_role;
ALTER TABLE recording_uploads ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE recording_uploads FROM PUBLIC, anon, authenticated, service_role;
REVOKE ALL ON ALL TABLES IN SCHEMA kynnected_private FROM PUBLIC, anon, authenticated, service_role;
